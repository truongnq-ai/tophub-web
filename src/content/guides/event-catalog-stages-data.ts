function resolveSeedCarryoverRule(seed: CatalogEventSeed, isPureRecharge: boolean): {
  readonly vi: string;
  readonly en: string;
} {
  if (isPureRecharge) {
    return {
      vi: "Sự kiện thuần nạp / gói ưu đãi (exchange): Tiến độ tích nạp chỉ tính trong thời gian mở sự kiện và tự động reset về 0 sau mốc 02:00 UTC (09:00 Giờ VN) ngày kết thúc.",
      en: "Pure recharge / bundle event (exchange): Cumulative top-up progress counts only while the event is live and resets to 0 after 02:00 UTC on the closing day.",
    };
  }
  if (seed.id.includes("wheel") || seed.id.includes("tavern") || seed.id.includes("recruit")) {
    return {
      vi: "Bảo lưu 100% đạo cụ quay (recycle = ''): Xu Vòng Quay (#204001) và Vé Chiêu Mộ (#204015) chưa dùng được giữ nguyên trong túi đồ sang các chu kỳ tiếp theo.",
      en: "100% token carryover (recycle = ''): Unused Wheel Tokens (#204001) and Recruit Tokens (#204015) remain in your inventory for future cycles.",
    };
  }
  if (
    seed.id.includes("festival") ||
    seed.id.includes("collab") ||
    seed.id.includes("pinball") ||
    seed.id.includes("bingo") ||
    seed.id.includes("fishing") ||
    seed.id.includes("box-gacha") ||
    seed.id.includes("dice")
  ) {
    return {
      vi: "Thu hồi đạo cụ sự kiện khi đóng Tiệm (recycle có hiệu lực): Đạo cụ rơi và xu đổi thưởng của kỳ này sẽ tự động thu hồi đổi sang Vàng/Tài nguyên thường khi kết thúc — bắt buộc đổi sạch Tiệm trước giờ chốt!",
      en: "Event tokens expire when the Shop closes (active recycle rule): Event drops and exchange coins convert into Gold/basic resources at event end — clear the Shop before reset!",
    };
  }
  return {
    vi: "Điểm đua mốc và BXH reset khi kết thúc kỳ lúc 02:00 UTC (09:00 Giờ VN); các nguyên liệu nâng cấp trong túi đồ (Mảnh Vàng, Đá Hồn, Orichalcum, Tăng Tốc) được bảo lưu 100%.",
    en: "Milestone and leaderboard points reset when the cycle closes at 02:00 UTC; all upgrade materials in your bag (Gold Shards, Soul Stones, Orichalcum, Speedups) carry over 100%.",
  };
}

function resolveCatalogHoardPrimaryIcon(seedId: string): string {
  if (/wheel/i.test(seedId)) return "/images/items/chests/icon_30059.webp";
  if (/dice|monopoly/i.test(seedId)) return "/images/items/chests/icon_30198.webp";
  if (/tavern|recruit|gacha/i.test(seedId)) return "/images/items/resources/icon_20013.webp";
  if (/pet/i.test(seedId)) return "/images/items/consumables/icon_30468.webp";
  if (/rune/i.test(seedId)) return "/images/items/chests/icon_30252.webp";
  if (/relic/i.test(seedId)) return "/images/items/consumables/icon_30397.webp";
  if (/blacksmith|lord-gear|orichalcum/i.test(seedId)) return "/images/items/materials/icon_material_3.webp";
  if (/exclusive-weapon/i.test(seedId)) return "/images/items/shards/icon_30511.webp";
  if (/soul-stone/i.test(seedId)) return "/images/items/shards/icon_30231.webp";
  if (/research|tech|dragon-essence|brilliance/i.test(seedId)) return "/images/items/materials/icon_30417.webp";
  if (/construction|castle|builder/i.test(seedId)) return "/images/items/consumables/icon_30017.webp";
  if (/troop/i.test(seedId)) return "/images/items/materials/icon_30018.webp";
  if (/skin|decor/i.test(seedId)) return "/images/items/currencies/icon_10029.webp";
  return "/images/items/shards/icon_30177.webp";
}

function resolveCatalogCustomShopIcon(nameVi: string, fallbackPath: string): string {
  if (/Đá Linh Hồn|Soul Stone/i.test(nameVi)) return "/images/items/shards/icon_30231.webp";
  if (/Vũ Khí Độc Quyền|Exclusive/i.test(nameVi)) return "/images/items/shards/icon_30511.webp";
  if (/Cổ Vật|Thánh Vật|Relic/i.test(nameVi)) return "/images/items/consumables/icon_30397.webp";
  if (/Cổ Ngữ|Rune/i.test(nameVi)) return "/images/items/chests/icon_30252.webp";
  if (/Thú Cưng|Pet/i.test(nameVi)) return "/images/items/consumables/icon_30468.webp";
  if (/Tinh Hoa Rồng|Dragon Essence/i.test(nameVi)) return "/images/items/materials/icon_30417.webp";
  if (/Orichalcum/i.test(nameVi)) return "/images/items/materials/icon_material_3.webp";
  if (/Ngoại Trang|Trang Trí|Skin|Decor/i.test(nameVi)) return "/images/items/currencies/icon_10029.webp";
  if (/Vé Di Cư|Transfer/i.test(nameVi)) return "/images/events/entry-icons/icon_kingdom_Migration.webp";
  return fallbackPath;
}

